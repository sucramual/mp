#!/usr/bin/env python3
"""Render a daily-digest Markdown file to an email-safe HTML file and a plain-text file.

Usage: python3 render.py <path>/<date>.md

Writes <date>.html and <date>.txt beside the input. Exit code 2, one line on stderr, and no files
when the digest breaks the structure that SKILL.md defines. Standard library only.
"""

from __future__ import annotations

import html
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import urlparse

MAX_WORDS = 1000
TITLE_PREFIX = "# Daily digest — "
SECTIONS = ("Yesterday", "Three concepts", "Today")
CHECK_PREFIX = "**Check yourself:**"
FOOTER = "Generated by daily-digest"

SANS = "-apple-system, 'Helvetica Neue', Arial, sans-serif"
SERIF = "Georgia, 'Times New Roman', serif"
INK = "#1c1917"
LINK = "#44403c"
HAIRLINE = "#e7e5e4"
SKY = "#3b82c4"

URL_RE = re.compile(r"https?://[^\s<>\]]+")
INLINE_RE = re.compile(
    r"`(?P<code>[^`]+)`"
    r"|\[(?P<label>[^\]]+)\]\((?P<target>(?:[^()\s]|\([^()\s]*\))+)\)"
    r"|\*\*(?P<bold>.+?)\*\*"
    r"|(?P<bare>https?://[^\s<>\]]+)"
)
PR_URL_RE = re.compile(r"https://github\.com/([\w.-]+/[\w.-]+)/pull/(\d+)")
LINEAR_URL_RE = re.compile(r"https://linear\.app/[\w.-]+/issue/([A-Za-z][A-Za-z0-9]*-\d+)")
WORD_RE = re.compile(r"\w[\w'’-]*")
BULLET_RE = re.compile(r"^[-*] +(.*)$")
NUMBERED_RE = re.compile(r"^(\d+)\. +(.*)$")
TRAILING_PUNCTUATION = ".,;:!?"


# --- Inline Markdown ------------------------------------------------------------------------------


def safe_url(url: str) -> str | None:
    """Return the URL when it is http or https with a host, otherwise None."""
    parsed = urlparse(url)
    if parsed.scheme in ("http", "https") and parsed.netloc:
        return url
    return None


def short_label(url: str) -> str | None:
    pr = PR_URL_RE.fullmatch(url)
    if pr:
        return f"{pr.group(1)}#{pr.group(2)}"
    issue = LINEAR_URL_RE.match(url)
    if issue:
        return issue.group(1).upper()
    return None


def link_html(label_html: str, url: str) -> str:
    return f'<a href="{html.escape(url, quote=True)}" style="color:{LINK};text-decoration:underline;">{label_html}</a>'


def inline(text: str) -> tuple[str, str]:
    """Convert one line of Markdown to (HTML, plain text). Raw HTML in the input is escaped."""
    out_html: list[str] = []
    out_text: list[str] = []
    pos = 0
    for match in INLINE_RE.finditer(text):
        plain = text[pos : match.start()]
        out_html.append(html.escape(plain))
        out_text.append(plain)
        pos = match.end()
        if match.group("code") is not None:
            code = match.group("code")
            out_html.append(
                f'<code style="font-family:Menlo, Consolas, monospace;font-size:0.9em;background:#f5f5f4;'
                f'padding:1px 4px;border-radius:3px;">{html.escape(code)}</code>'
            )
            out_text.append(code)
        elif match.group("bold") is not None:
            inner_html, inner_text = inline(match.group("bold"))
            out_html.append(f"<strong>{inner_html}</strong>")
            out_text.append(inner_text)
        elif match.group("label") is not None:
            label = match.group("label")
            url = safe_url(match.group("target"))
            if url is None:
                out_html.append(html.escape(label))
                out_text.append(label)
            else:
                out_html.append(link_html(html.escape(label), url))
                out_text.append(f"{label} ({url})")
        else:
            bare = match.group("bare")
            trail = ""
            # A ")" closes the prose around the URL unless the URL itself opened a "(".
            while bare and (
                bare[-1] in TRAILING_PUNCTUATION or (bare[-1] == ")" and bare.count("(") < bare.count(")"))
            ):
                trail = bare[-1] + trail
                bare = bare[:-1]
            url = safe_url(bare)
            if url is None:
                out_html.append(html.escape(bare))
                out_text.append(bare)
            else:
                label = short_label(url)
                out_html.append(link_html(html.escape(label or url), url))
                out_text.append(f"{label} ({url})" if label else url)
            out_html.append(html.escape(trail))
            out_text.append(trail)
    out_html.append(html.escape(text[pos:]))
    out_text.append(text[pos:])
    return "".join(out_html), "".join(out_text)


# --- Block parsing --------------------------------------------------------------------------------


@dataclass
class Block:
    kind: str  # h1, h2, h3, p, ul, ol
    text: str = ""
    items: list[str] = field(default_factory=list)


def parse_blocks(markdown: str) -> list[Block]:
    blocks: list[Block] = []
    paragraph: list[str] = []

    def flush() -> None:
        if paragraph:
            blocks.append(Block("p", " ".join(paragraph)))
            paragraph.clear()

    for raw in markdown.splitlines():
        line = raw.rstrip()
        stripped = line.strip()
        bullet = BULLET_RE.match(stripped)
        numbered = NUMBERED_RE.match(stripped)
        last = blocks[-1] if blocks else None
        if not stripped:
            flush()
        elif stripped.startswith("#"):
            flush()
            level = len(stripped) - len(stripped.lstrip("#"))
            if 1 <= level <= 3 and stripped[level : level + 1] == " ":
                blocks.append(Block(f"h{level}", stripped[level + 1 :].strip()))
            else:
                paragraph.append(stripped)
        elif bullet and not raw.startswith((" ", "\t")):
            flush()
            if last and last.kind == "ul":
                last.items.append(bullet.group(1))
            else:
                blocks.append(Block("ul", items=[bullet.group(1)]))
        elif numbered and not raw.startswith((" ", "\t")):
            flush()
            if last and last.kind == "ol":
                last.items.append(numbered.group(2))
            else:
                blocks.append(Block("ol", items=[numbered.group(2)]))
        elif raw.startswith((" ", "\t")) and last and last.kind in ("ul", "ol") and not paragraph:
            last.items[-1] += " " + stripped
        elif stripped.startswith(("**Why it mattered:**", CHECK_PREFIX)):
            flush()
            paragraph.append(stripped)
        else:
            paragraph.append(stripped)
    flush()
    return blocks


# --- Validation -----------------------------------------------------------------------------------


def count_words(markdown: str) -> int:
    return len(WORD_RE.findall(URL_RE.sub(" ", markdown)))


def validate(markdown: str, blocks: list[Block]) -> str | None:
    """Return one specific error message, or None when the digest is valid."""
    first = next((line for line in markdown.splitlines() if line.strip()), "")
    if not first.startswith(TITLE_PREFIX) or not first[len(TITLE_PREFIX) :].strip():
        return f"the first line must start with '{TITLE_PREFIX}' followed by the date"
    if not any(line.startswith("Covers:") for line in markdown.splitlines()):
        return "missing the 'Covers:' line"
    names = [b.text for b in blocks if b.kind == "h2"]
    for section in SECTIONS:
        if section not in names:
            return f"missing the '## {section}' section"
    if names != list(SECTIONS):
        return "the sections must be '## Yesterday', '## Three concepts', '## Today' in this order"
    concepts = section_blocks(blocks, "Three concepts")
    headings = [b.text for b in concepts if b.kind == "h3"]
    if len(headings) != 3 or [h.split(".", 1)[0] for h in headings] != ["1", "2", "3"]:
        return "'## Three concepts' needs exactly three concepts, headed '### 1.', '### 2.' and '### 3.'"
    for number, body in enumerate(split_concepts(concepts), start=1):
        if not any(b.kind == "p" and b.text.startswith(CHECK_PREFIX) for b in body):
            return f"concept {number} has no '{CHECK_PREFIX}' line"
    today = section_blocks(blocks, "Today")
    items = sum(len(b.items) for b in today if b.kind == "ol")
    if not 1 <= items <= 3:
        return f"'## Today' needs 1 to 3 numbered items, found {items}"
    words = count_words(markdown)
    if words > MAX_WORDS:
        return f"the digest has {words} words, over the {MAX_WORDS}-word limit"
    return None


def section_blocks(blocks: list[Block], name: str) -> list[Block]:
    out: list[Block] = []
    inside = False
    for block in blocks:
        if block.kind == "h2":
            inside = block.text == name
        elif inside:
            out.append(block)
    return out


def split_concepts(blocks: list[Block]) -> list[list[Block]]:
    """Group the blocks of '## Three concepts' by their '###' heading. The heading is the first block."""
    groups: list[list[Block]] = []
    for block in blocks:
        if block.kind == "h3":
            groups.append([block])
        elif groups:
            groups[-1].append(block)
    return groups


def concept_name(heading: str) -> tuple[str, str]:
    number, _, name = heading.partition(".")
    return number.strip(), name.strip()


# --- HTML -----------------------------------------------------------------------------------------


def h(text: str) -> str:
    return inline(text)[0]


def p_html(text: str, extra: str = "") -> str:
    return f'<p style="margin:0 0 12px 0;{extra}">{h(text)}</p>'


def list_html(block: Block) -> str:
    items = "".join(f'<li style="margin:0 0 6px 0;">{h(item)}</li>' for item in block.items)
    return f'<ul style="margin:0 0 12px 0;padding-left:22px;">{items}</ul>'


def h2_html(text: str) -> str:
    return (
        f'<h2 style="margin:32px 0 14px 0;padding-top:16px;border-top:1px solid {HAIRLINE};font-family:{SANS};'
        f"font-size:12px;font-weight:600;line-height:1.4;text-transform:uppercase;letter-spacing:1px;"
        f'color:#57534e;">{html.escape(text)}</h2>'
    )


def h3_html(text: str) -> str:
    return (
        f'<h3 style="margin:20px 0 6px 0;font-family:{SANS};font-size:15px;font-weight:600;line-height:1.4;'
        f'color:{INK};">{h(text)}</h3>'
    )


def concept_card_html(group: list[Block]) -> str:
    number, name = concept_name(group[0].text)
    parts = [
        f'<div style="font-family:{SANS};font-size:13px;font-weight:700;color:{SKY};letter-spacing:0.5px;">'
        f"{html.escape(number)}</div>",
        f'<h3 style="margin:2px 0 10px 0;font-family:{SANS};font-size:15px;font-weight:600;line-height:1.4;'
        f'color:{INK};">{h(name)}</h3>',
    ]
    for block in group[1:]:
        if block.kind == "p" and block.text.startswith(CHECK_PREFIX):
            parts.append(
                f'<div style="margin:14px 0 0 0;padding:12px 14px;background:#eef5fb;border-radius:6px;'
                f'font-size:16px;line-height:1.5;">{h(block.text)}</div>'
            )
        elif block.kind == "p":
            parts.append(p_html(block.text, "font-size:16px;"))
        elif block.kind in ("ul", "ol"):
            parts.append(list_html(block))
    return (
        '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" '
        f'style="margin:0 0 16px 0;background:#ffffff;border:1px solid {HAIRLINE};border-radius:8px;">'
        f'<tr><td style="padding:20px;font-family:{SERIF};color:{INK};">{"".join(parts)}</td></tr></table>'
    )


def today_html(block: Block) -> str:
    rows = []
    for number, item in enumerate(block.items, start=1):
        rows.append(
            f'<tr><td width="40" valign="top" style="padding:0 0 14px 0;font-family:{SANS};font-size:26px;'
            f'font-weight:600;line-height:1.2;color:{SKY};">{number}</td>'
            f'<td valign="top" style="padding:2px 0 14px 0;font-family:{SERIF};font-size:17px;line-height:1.6;'
            f'color:{INK};">{h(item)}</td></tr>'
        )
    return f'<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">{"".join(rows)}</table>'


def body_html(blocks: list[Block]) -> str:
    out: list[str] = []
    section = ""
    concept_groups: list[list[Block]] = []

    def flush_cards() -> None:
        out.extend(concept_card_html(group) for group in concept_groups)
        concept_groups.clear()

    for block in blocks:
        if block.kind == "h2":
            flush_cards()
            section = block.text
            out.append(h2_html(block.text))
        elif block.kind in ("h1",):
            continue
        elif section == "Three concepts":
            if block.kind == "h3":
                concept_groups.append([block])
            elif concept_groups:
                concept_groups[-1].append(block)
        elif block.kind == "h3":
            out.append(h3_html(block.text))
        elif block.kind == "p" and not block.text.startswith("Covers:") and section:
            out.append(p_html(block.text))
        elif block.kind == "ul":
            out.append(list_html(block))
        elif block.kind == "ol":
            out.append(today_html(block) if section == "Today" else list_html(block))
    flush_cards()
    return "".join(out)


def render_html(markdown: str) -> str:
    blocks = parse_blocks(markdown)
    title = next(b.text for b in blocks if b.kind == "h1")[len("Daily digest — ") :]
    covers = next((line for line in markdown.splitlines() if line.startswith("Covers:")), "")
    plain_title = html.escape(f"Daily digest — {title}")
    return (
        '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>{plain_title}</title></head>"
        '<body style="margin:0;padding:0;background:#f7f7f5;">'
        '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" '
        'style="background:#f7f7f5;">'
        '<tr><td style="height:6px;line-height:6px;font-size:0;background:#cfe3f5;">&nbsp;</td></tr>'
        '<tr><td align="center" style="padding:0 12px 40px 12px;">'
        '<table role="presentation" width="560" cellpadding="0" cellspacing="0" border="0" '
        'style="width:100%;max-width:560px;">'
        f'<tr><td style="padding:32px 0 8px 0;">'
        f'<div style="font-family:{SANS};font-size:11px;letter-spacing:1.5px;color:#78716c;">DAILY DIGEST</div>'
        f'<h1 style="margin:8px 0 8px 0;font-family:{SERIF};font-size:30px;font-weight:400;letter-spacing:-0.5px;'
        f'line-height:1.2;color:{INK};">{html.escape(title)}</h1>'
        f'<div style="font-family:{SANS};font-size:13px;line-height:1.5;color:#78716c;">{h(covers)}</div>'
        "</td></tr>"
        f'<tr><td style="font-family:{SERIF};font-size:17px;line-height:1.6;color:{INK};">{body_html(blocks)}</td></tr>'
        f'<tr><td style="padding:32px 0 0 0;font-family:{SANS};font-size:11px;color:#a8a29e;">{FOOTER}</td></tr>'
        "</table></td></tr></table></body></html>\n"
    )


# --- Plain text -----------------------------------------------------------------------------------


def render_text(markdown: str) -> str:
    blocks = parse_blocks(markdown)
    title = next(b.text for b in blocks if b.kind == "h1")[len("Daily digest — ") :]
    covers = next((line for line in markdown.splitlines() if line.startswith("Covers:")), "")
    lines = ["DAILY DIGEST", title, inline(covers)[1], ""]
    section = ""
    for block in blocks:
        if block.kind == "h1":
            continue
        if block.kind == "h2":
            section = block.text
            lines += ["", block.text.upper(), "-" * len(block.text), ""]
        elif block.kind == "h3":
            number, name = (block.text.split(".", 1) + [""])[:2] if section == "Three concepts" else ("", "")
            lines += ["", f"{number}. {name.strip()}" if name else inline(block.text)[1]]
        elif block.kind == "p" and not block.text.startswith("Covers:"):
            lines += [inline(block.text)[1], ""]
        elif block.kind == "ul":
            lines += [f"- {inline(item)[1]}" for item in block.items] + [""]
        elif block.kind == "ol":
            lines += [f"{n}. {inline(item)[1]}" for n, item in enumerate(block.items, start=1)] + [""]
    lines += ["", FOOTER]
    text = "\n".join(lines)
    return re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"


# --- CLI ------------------------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        print("usage: render.py <path>/<date>.md", file=sys.stderr)
        return 2
    path = Path(args[0])
    try:
        markdown = path.read_text(encoding="utf-8")
    except OSError as error:
        print(f"cannot read {path}: {error.strerror or error}", file=sys.stderr)
        return 2
    error_message = validate(markdown, parse_blocks(markdown))
    if error_message:
        print(f"{path.name}: {error_message}", file=sys.stderr)
        return 2
    path.with_suffix(".html").write_text(render_html(markdown), encoding="utf-8")
    path.with_suffix(".txt").write_text(render_text(markdown), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
